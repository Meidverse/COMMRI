"""Insert app screenshots (Figs 4.4–4.8) into a COPY of the synergy report, matching existing figure style."""
import copy
import os
import sys

import docx
from docx.shared import Inches
from docx.text.paragraph import Paragraph

SRC, DST = sys.argv[1], sys.argv[2]
FIG = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "report_figures")

# (insert after the last paragraph of this section heading, figure file, caption, width or height)
PLAN = [
    ("4.3 Backend and AI Model Implementation", [
        ("fig_4_4_image_upload.png", "Fig. 4.4: Medical Image Upload Interface", {"width": Inches(5.6)}),
        ("fig_4_5_image_processing.png", "Fig. 4.5: Medical Image Preprocessing and Analysis", {"width": Inches(5.6)}),
    ]),
    ("4.4 Testing and Evaluation", [
        ("fig_4_6_analysis_result.png", "Fig. 4.6: Output Generated by the Medical Image Analysis System", {"width": Inches(5.6)}),
    ]),
    ("4.5 Results and Observations", [
        ("fig_4_7_result_report.png", "Fig. 4.7: Generated Medical Image Analysis Report", {"height": Inches(7.4)}),
        ("fig_4_8_analysis_history.png", "Fig. 4.8: Analysis History and Patient Records Interface", {"width": Inches(5.6)}),
    ]),
]

d = docx.Document(SRC)
paras = d.paragraphs
caption_tpl = next(p for p in paras if p.text.strip().startswith("Fig. 4.3:"))
pic_tpl = paras[paras.index(caption_tpl) - 1]
assert pic_tpl._p.xpath(".//w:drawing"), "expected picture paragraph before Fig. 4.3 caption"


def section_end(heading):
    start = next(i for i, p in enumerate(paras) if p.text.strip() == heading)
    i = start + 1
    while i < len(paras) and not paras[i].style.name.startswith("Heading"):
        i += 1
    j = i - 1
    while j > start and not paras[j].text.strip() and not paras[j]._p.xpath(".//w:drawing"):
        j -= 1  # skip trailing blank paragraphs
    return paras[j]


def clone_after(anchor, tpl):
    new = copy.deepcopy(tpl._p)
    for r in new.xpath("./w:r | ./w:hyperlink"):
        new.remove(r)
    anchor._p.addnext(new)
    return Paragraph(new, anchor._parent)


for heading, figs in PLAN:
    anchor = section_end(heading)
    for fname, caption, size in figs:
        pic = clone_after(anchor, pic_tpl)
        pic.paragraph_format.keep_with_next = True
        pic.add_run().add_picture(os.path.join(FIG, fname), **size)
        cap = clone_after(pic, caption_tpl)
        src_run = caption_tpl.runs[0]._r
        run = copy.deepcopy(src_run)
        for t in run.xpath("./w:t"):
            run.remove(t)
        cap._p.append(run)
        cap.runs[-1].text = caption
        anchor = cap
        print("inserted", caption)

d.save(DST)
print("saved", DST)
