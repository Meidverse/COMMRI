"""Final report edits (on a copy): declaration title, Fig 4.1-4.3 from the current app, remove Flask row,
rebuild List of Figures rows. Page numbers are filled afterwards by Word (scripts/update_pages.ps1)."""
import copy
import os
import sys

import docx
from docx.shared import Inches
from docx.text.paragraph import Paragraph

SRC, DST = sys.argv[1], sys.argv[2]
FIG = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "report_figures")
TITLE = "Medical Image Analysis for Disease Detection"

d = docx.Document(SRC)
P = d.paragraphs

# 1. declaration title
decl = next(p for p in P if "hereby declare that this report entitled" in p.text)
c_run = next(r for r in decl.runs if r.text.strip() == "C")
c_run.text = TITLE
print("declaration:", decl.text[150:260])

# 2. replace Fig 4.1 / 4.3 images with screenshots of the current application
def pic_before(caption_start):
    ps = d.paragraphs
    i = next(k for k, p in enumerate(ps) if p.text.strip().startswith(caption_start))
    cap, pic = ps[i], ps[i - 1]
    assert pic._p.xpath(".//w:drawing")
    return cap, pic

def replace_pic(pic, path, width):
    for r in pic._p.xpath("./w:r[.//w:drawing]"):
        pic._p.remove(r)
    pic.add_run().add_picture(path, width=width)
    pic.paragraph_format.keep_with_next = True

cap41, pic41 = pic_before("Fig. 4.1:")
cap43, pic43 = pic_before("Fig. 4.3:")
replace_pic(pic41, os.path.join(FIG, "fig_4_1_registration.png"), Inches(5.6))
replace_pic(pic43, os.path.join(FIG, "fig_4_3_dashboard.png"), Inches(5.6))
cap41.alignment = cap43.alignment  # was justified; centre like other captions

# 3. insert Fig 4.2 (login) after Fig 4.1 caption
new_pic = copy.deepcopy(pic43._p)
for r in new_pic.xpath("./w:r"):
    new_pic.remove(r)
cap41._p.addnext(new_pic)
pic42 = Paragraph(new_pic, cap41._parent)
pic42.add_run().add_picture(os.path.join(FIG, "fig_4_2_login.png"), width=Inches(5.6))
pic42.paragraph_format.keep_with_next = True
new_cap = copy.deepcopy(cap43._p)
pic42._p.addnext(new_cap)
cap42 = Paragraph(new_cap, cap41._parent)
for r in cap42.runs[1:]:
    r._r.getparent().remove(r._r)
cap42.runs[0].text = "Fig. 4.2: User Login Interface of the Medical Image Analysis System"

# 4. remove Flask row from Software Requirements table
for t in d.tables:
    for row in list(t.rows):
        if row.cells[0].text.strip() == "Flask":
            row._tr.getparent().remove(row._tr)
            print("removed Flask row")

# 5. rebuild List of Figures rows
lof = next(t for t in d.tables if t.rows[0].cells[0].text.strip() == "Figures No.")
template = copy.deepcopy(lof.rows[1]._tr)
for row in list(lof.rows)[1:]:
    row._tr.getparent().remove(row._tr)
FIGS = [
    ("Figure 3.1", "System Architecture of the Medical Image Analysis System"),
    ("Figure 4.1", "User Registration Interface of the Medical Image Analysis System"),
    ("Figure 4.2", "User Login Interface of the Medical Image Analysis System"),
    ("Figure 4.3", "Main Dashboard of the Medical Image Analysis System"),
    ("Figure 4.4", "Medical Image Upload Interface"),
    ("Figure 4.5", "Medical Image Preprocessing and Analysis"),
    ("Figure 4.6", "Output Generated by the Medical Image Analysis System"),
    ("Figure 4.7", "Generated Medical Image Analysis Report"),
    ("Figure 4.8", "Analysis History and Patient Records Interface"),
]
for no, name in FIGS:
    tr = copy.deepcopy(template)
    lof._tbl.append(tr)
    row = lof.rows[-1]
    for cell, val in zip(row.cells, (no, name, "00")):
        p = cell.paragraphs[0]
        for r in p.runs[1:]:
            r._r.getparent().remove(r._r)
        p.runs[0].text = val
print("list of figures rows:", len(lof.rows) - 1)

d.save(DST)
print("saved", DST)
